const { createVimEngine } = require('../js/vim-engine.js');
let pass = 0, fail = 0;
function toks(s){
  const out = []; const re = /<(?:[CS]-)?[A-Za-z\[\]]+>|[\s\S]/gu; let m;
  while ((m = re.exec(s))) out.push(m[0]);
  return out;
}
function mk(text, hooks = {}){
  const E = createVimEngine(hooks);
  E.load(text);
  return E;
}
function t(name, text, keys, expText, expCur, opt = {}){
  const written = [];
  const E = mk(text, { write: (x) => { written.push(x); return { ok:true, msg:'w' }; }, quit(){}, ...opt.hooks });
  if (opt.cur) E.setCursor(opt.cur[0], opt.cur[1]);
  let error = null;
  try { for (const k of toks(keys)) E.feed(k); } catch (e) { error = e; }
  const got = E.getText();
  const okT = expText === undefined || got === expText;
  const okC = !expCur || (E.cur.line === expCur[0] && E.cur.col === expCur[1]);
  const okM = !opt.mode || E.mode === opt.mode;
  const okMsg = !opt.msg || (E.msg || '').includes(opt.msg);
  if (okT && okC && okM && okMsg && !error) pass++;
  else {
    fail++;
    console.log(`FAIL ${name}\n  keys: ${keys}\n  got:  ${JSON.stringify(got)} cur=${E.cur.line},${E.cur.col} mode=${E.mode} msg=${E.msg}\n  want: ${JSON.stringify(expText)} cur=${expCur} ${opt.mode || ''} ${opt.msg || ''}${error ? '\n  ERROR ' + error.stack : ''}`);
  }
  return E;
}
